export function eventsAtVenue<
  T extends { location?: string | null; latitude?: number | null; longitude?: number | null },
>(events: T[], venue: KeVenue): T[] {
  const name = venue.name.toLowerCase();
  return events.filter((event) => {
    const loc = (event.location || '').toLowerCase();
    if (loc && (loc.includes(name) || name.split(' ').every((part) => part.length > 2 && loc.includes(part)))) {
      return true;
    }
    const lat = event.latitude != null ? Number(event.latitude) : NaN;
    const lng = event.longitude != null ? Number(event.longitude) : NaN;
    if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
    return Math.abs(lat - venue.latitude) < 0.0018 && Math.abs(lng - venue.longitude) < 0.0018;
  });
}
